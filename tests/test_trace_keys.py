def test_recording_window_receives_keys_at_the_real_receiver(recording, caplog):
    """As main() opens it (Tracking Lab on, Qt's own initial focus): keys sent to the QWindow, which is
    where the platform delivers them (diagnosed with a spy on the real main()), reach the recorder."""
    app, window, path = recording
    window.set_lab_mode(True)
    app.debug_keys = True
    QApplication.processEvents()
    handle = window.windowHandle()
    assert handle is not None
    with caplog.at_level("WARNING", logger="handpiano.app.application"):
        for code, _, _ in HOME_ROW:
            QTest.keyClick(handle, code)
    QApplication.processEvents()
    assert [e.key for e in app.trace.key_events if e.down] == ["A", "S", "D", "F", "J", "K", "L", "Ñ"]
    assert sum(not e.down for e in app.trace.key_events) == 8
    lines = [r.getMessage() for r in caplog.records if r.getMessage().startswith("[teclado] PRESS")
             or r.getMessage().startswith("[teclado] RELEASE")]
    assert len(lines) == 16  # one line per press/release, not one per widget that sees the event
    assert "PRESS código=0x41" in lines[0] and "receptor=QWindow" in lines[0] and "registrador: SÍ (A, 1" in lines[0]
    assert "código=0xd1" in lines[14] and "registrador: SÍ (Ñ" in lines[14]
    finish(app)
    assert len(load_labels(sidecar_paths(path)["labels"])) == 16


def test_focus_changes_are_reported_on_the_console(recording, caplog):
    app, _, _ = recording
    with caplog.at_level("WARNING", logger="handpiano.app.application"):
        app._on_application_state(Qt.ApplicationState.ApplicationInactive)
        app._on_application_state(Qt.ApplicationState.ApplicationActive)
    messages = [r.getMessage() for r in caplog.records]
    assert any("dejó de ser la app activa" in m for m in messages)
    assert any("es la app activa" in m for m in messages)

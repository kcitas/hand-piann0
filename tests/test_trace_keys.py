"""Keys protocol, end to end without a camera: Qt key events → filter → recorder → .labels.csv.

Reproduces teclado_1/2 (a complete keys recording with 0 key events and no labels) and
checks what makes it visible. Keys are delivered with QTest (QApplication dispatch, event
filters included); the real macOS path is checked by scripts/check_trace_keys.py
(opt-in test at the end).
"""


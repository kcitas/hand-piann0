HOME_ROW = ((Qt.Key.Key_A, "a", "LEFT_PINKY"), (Qt.Key.Key_S, "s", "LEFT_RING"),
            (Qt.Key.Key_D, "d", "LEFT_MIDDLE"), (Qt.Key.Key_F, "f", "LEFT_INDEX"),
            (Qt.Key.Key_J, "j", "RIGHT_INDEX"), (Qt.Key.Key_K, "k", "RIGHT_MIDDLE"),
            (Qt.Key.Key_L, "l", "RIGHT_RING"), (Qt.Key.Key_Ntilde, "ñ", "RIGHT_PINKY"))


class RunningPipeline:
    state = PipelineState.RUNNING
    frame_listener = None


@pytest.fixture
def recording(tmp_path):
    QApplication.instance() or QApplication([])
    window = MainWindow(CameraSettings())
    window.show()
    app = Application(AppConfig(), window, audio=AudioEngine(sounds_dir=tmp_path / "no_sounds"))
    path = tmp_path / "teclado_test.csv"
    app.request_trace(path, "keys")
    yield app, window, path
    app.trace = None
    app.shutdown()
    window.close()


def finish(app):
    """Jumps past the last step: the recording is written exactly as at the end of a real one."""
    app._trace_started_at = time.monotonic() - sum(s.duration_s for s in app.trace.steps) - 1
    trace = app.trace
    app._update_trace(RunningPipeline())
    return trace


def press_release(widget, code, text):
    QApplication.sendEvent(widget, QKeyEvent(QEvent.Type.KeyPress, code, Qt.KeyboardModifier.NoModifier, text))
    QApplication.sendEvent(widget, QKeyEvent(QEvent.Type.KeyRelease, code, Qt.KeyboardModifier.NoModifier, text))


def test_every_home_row_key_becomes_a_valid_label(recording):
    app, window, path = recording
    for code, text, _ in HOME_ROW:
        press_release(window, code, text)  # through QApplication: the event filter is on the real path
    QTest.keyClick(window.camera_view, Qt.Key.Key_J)  # QTest: another widget, text generated by Qt
    trace = finish(app)
    files = sidecar_paths(path)
    assert files["labels"].is_file()
    labels = load_labels(files["labels"])  # validates every row
    contacts = [(lb.target, lb.note) for lb in labels if lb.label == "contact"]
    releases = [(lb.target, lb.note) for lb in labels if lb.label == "release"]
    expected = [(finger, f"key={text.upper()}") for _, text, finger in HOME_ROW] + [("RIGHT_INDEX", "key=J")]
    assert contacts == expected and releases == expected
    assert all(lb.source == "keyboard" and lb.confidence == "confirmed" for lb in labels)
    assert all(a.t_start <= b.t_start for a, b in itertools.pairwise(labels))
    assert trace.key_count == 18
    assert window.camera_view._banner[0] == "Grabación terminada"
    assert "Teclas registradas: 18 eventos (9 pulsaciones)" in window.camera_view._banner[1][1]


def test_no_keys_reproduces_the_empty_recordings_and_says_so(recording):
    """teclado_1/2: a full keys recording where no key reached the app → no labels, and the UI says it."""
    app, window, path = recording
    window.isActiveWindow = lambda: True
    steps = app.trace.steps
    first_tap = next(i for i, s in enumerate(steps) if s.name.startswith("key_taps"))
    app._trace_started_at = time.monotonic() - (sum(s.duration_s for s in steps[:first_tap])
                                                + steps[first_tap].cue_times()[0] + 0.1)
    app._update_trace(RunningPipeline())  # the first tap cue: flash banner
    title, lines, _, color = window.camera_view._banner
    assert title == "¡TOCA!" and "⚠ NO LLEGA NINGUNA TECLA" in lines and color.name() == "#f87171"
    app._cue_shown_at = None
    app._update_trace(RunningPipeline())
    title, lines, _, _ = window.camera_view._banner
    assert title == "⚠ NO LLEGA NINGUNA TECLA" and any("Teclas registradas: 0" in line for line in lines)
    trace = finish(app)
    assert trace.key_count == 0 and not sidecar_paths(path)["labels"].exists()  # nothing invented
    title, lines, _, _ = window.camera_view._banner
    assert title == "Grabación terminada SIN etiquetas" and "NO hay etiquetas" in lines[1]


def test_lost_focus_is_reported_from_the_start(recording):
    app, window, _ = recording
    window.isActiveWindow = lambda: False
    app._trace_started_at = time.monotonic() - 1.0  # still in "prepare"
    app._update_trace(RunningPipeline())
    assert window.camera_view._banner[0] == "⚠ LA VENTANA NO TIENE EL FOCO DEL TECLADO"
    window.isActiveWindow = lambda: True
    app._update_trace(RunningPipeline())
    assert window.camera_view._banner[0].startswith("Dedos sobre la fila central")


def test_counter_is_visible_and_counts_presses(recording):
    _, window, _ = recording
    assert window.trace_keys_label.isVisible() and "0 eventos" in window.trace_keys_label.text()
    press_release(window, Qt.Key.Key_F, "f")
    press_release(window, Qt.Key.Key_F, "f")
    press_release(window, Qt.Key.Key_Ntilde, "ñ")
    assert window.trace_keys_label.text() == "Teclas registradas: 6 eventos · pulsaciones F:2 Ñ:1"


def test_release_without_text_or_with_a_modifier_still_matches_its_press(recording):
    """Identity comes from the key code: a release whose text differs must not leave the key 'held'."""
    app, window, _ = recording
    send = QApplication.sendEvent
    send(window, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_L, Qt.KeyboardModifier.NoModifier, "l"))
    send(window, QKeyEvent(QEvent.Type.KeyRelease, Qt.Key.Key_L, Qt.KeyboardModifier.NoModifier, ""))
    send(window, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_L, Qt.KeyboardModifier.AltModifier, "¬"))
    send(window, QKeyEvent(QEvent.Type.KeyRelease, Qt.Key.Key_L, Qt.KeyboardModifier.NoModifier, "l"))
    assert [(e.key, e.down) for e in app.trace.key_events] == [("L", True), ("L", False), ("L", True), ("L", False)]


def test_auto_repeat_and_duplicate_delivery_add_no_events(recording):
    app, window, _ = recording
    send = QApplication.sendEvent
    send(window, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_D, Qt.KeyboardModifier.NoModifier, "d"))
    send(window.camera_view, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_D, Qt.KeyboardModifier.NoModifier, "d"))
    send(window, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_D, Qt.KeyboardModifier.NoModifier, "d", True))
    send(window, QKeyEvent(QEvent.Type.KeyRelease, Qt.Key.Key_D, Qt.KeyboardModifier.NoModifier, "d"))
    assert [(e.key, e.down) for e in app.trace.key_events] == [("D", True), ("D", False)]


def test_existing_files_are_never_overwritten(recording, tmp_path):
    app, window, path = recording
    files = sidecar_paths(path)
    files["labels"].write_text("previous labels\n")  # e.g. a hand-made label file with the same name
    press_release(window, Qt.Key.Key_A, "a")
    finish(app)
    assert files["labels"].read_text() == "previous labels\n"
    assert not path.exists() and window.camera_view._banner[0] == "Traza NO guardada"


def test_key_names():
    def name(code, text, mods=Qt.KeyboardModifier.NoModifier):
        return trace_key_name(QKeyEvent(QEvent.Type.KeyPress, code, mods, text))

    assert name(Qt.Key.Key_A, "a") == "A" and name(Qt.Key.Key_Ntilde, "") == "Ñ"
    assert name(Qt.Key.Key_Semicolon, ";") == ";" and name(Qt.Key.Key_L, "¬", Qt.KeyboardModifier.AltModifier) == "L"
    assert name(Qt.Key.Key_Shift, "") == "" and name(Qt.Key.Key_1, "1") == "1"


